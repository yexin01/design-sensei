#!/usr/bin/env python3
"""Build the indexes of Design Sensei.

``design-sensei index build``            index the local source library (file level) into the state directory
``design-sensei index build --docs``     also regenerate knowledge/pattern-index/ (browsable Markdown + JSON)
``design-sensei index build --check``    verify the generated pattern index is up to date (exit 1 if stale)

The pattern index is derived only from catalog/*.yaml and knowledge/ notes, contains
no timestamps and is byte-for-byte reproducible, so it can be committed and reviewed.
The source index is derived from downloaded upstream files, stays local and is never
committed.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any, Dict, List, Optional, Sequence

if __package__ in (None, ""):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import index_sources
from dslib import EXIT_FAILURE, EXIT_OK
from dslib import catalog, knowledge
from dslib.cli import add_global_options, eprint, fail, print_json, run_with_layout
from dslib.paths import Layout
from dslib.textutil import truncate

HEADER = "<!-- Generated by `design-sensei index build --docs`. Do not edit by hand. -->\n\n"


def _row(cells: Sequence[str]) -> str:
    return "| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in cells) + " |"


def _pattern_link(p: Dict[str, Any]) -> str:
    return "`%s`" % p["id"]


def _enrich(layout: Layout) -> List[Dict[str, Any]]:
    sources = catalog.by_id(catalog.load_sources(layout))
    out = []
    for p in sorted(catalog.load_patterns(layout), key=lambda x: x["id"]):
        sids = list(p.get("source_ids") or [])
        redis = catalog.derive_redistribution(sids, sources) if sids else "original"
        item = dict(p)
        item["license_status"] = catalog.derive_license_status(sids, sources) if sids else "verified"
        item["redistribution_status"] = redis
        item["reuse"] = catalog.reuse_for(redis)[0] if sids else "original"
        out.append(item)
    return out


def generate_docs(layout: Layout) -> Dict[str, str]:
    """Return {relative path under knowledge/pattern-index: file text}."""
    patterns = _enrich(layout)
    sources = catalog.load_sources(layout)
    docs = [d for d in knowledge.iter_docs(layout) if d.meta]
    files = {}  # type: Dict[str, str]

    # --- by-category.md ----------------------------------------------------
    lines = [HEADER + "# Patterns by category\n"]
    cats = sorted({p["category"] for p in patterns})
    for cat in cats:
        group = [p for p in patterns if p["category"] == cat]
        lines.append("## %s (%d)\n" % (cat, len(group)))
        lines.append(_row(["Pattern", "Title", "Summary", "Sources", "Licence status", "Reuse", "Status"]))
        lines.append(_row(["---"] * 7))
        for p in group:
            lines.append(_row([_pattern_link(p), p["title"], truncate(p["summary"], 140), ", ".join(p.get("source_ids") or []) or "original",
                               p["license_status"], p["reuse"], p["implementation_status"]]))
        lines.append("")
    files["by-category.md"] = "\n".join(lines)

    # --- by-source.md ------------------------------------------------------
    lines = [HEADER + "# Patterns and notes by source\n"]
    for s in sources:
        sp = [p for p in patterns if s["id"] in (p.get("source_ids") or [])]
        sd = [d for d in docs if s["id"] in (d.meta.get("source_ids") or [])]  # type: ignore[union-attr]
        reuse = catalog.reuse_for(s["redistribution_status"])
        lines.append("## %s (`%s`)\n" % (s["name"], s["id"]))
        lines.append("- URL: %s" % s["url"])
        lines.append("- License: `%s` (%s); redistribution: %s; reuse: **%s**" % (s["license"], s["license_status"], s["redistribution_status"], reuse[0]))
        lines.append("- Acquisition: %s; pinned commit: %s" % (s["acquisition_method"], ("`%s`" % s["pinned_commit"][:12]) if s.get("pinned_commit") else "-"))
        lines.append("- Patterns (%d): %s" % (len(sp), ", ".join(_pattern_link(p) for p in sp) or "-"))
        lines.append("- Notes (%d): %s" % (len(sd), ", ".join("[%s](../%s)" % (d.meta["title"], d.rel[len("knowledge/"):]) for d in sd) or "-"))  # type: ignore[index]
        lines.append("")
    files["by-source.md"] = "\n".join(lines)

    # --- by-framework.md / by-tag.md --------------------------------------
    for fname, field, title in (("by-framework.md", "frameworks", "Patterns by framework"), ("by-tag.md", "tags", "Patterns by tag")):
        buckets = {}  # type: Dict[str, List[str]]
        for p in patterns:
            for v in p.get(field, []):
                buckets.setdefault(v, []).append(p["id"])
        lines = [HEADER + "# %s\n" % title]
        for key in sorted(buckets):
            lines.append("- **%s** (%d): %s" % (key, len(buckets[key]), ", ".join("`%s`" % i for i in buckets[key])))
        files[fname] = "\n".join(lines) + "\n"

    # --- notes.md ------------------------------------------------------------
    lines = [HEADER + "# Knowledge notes\n"]
    folders = {}  # type: Dict[str, List[Any]]
    for d in docs:
        folders.setdefault(d.rel.split("/")[1] if d.rel.count("/") > 1 else ".", []).append(d)
    for folder in sorted(folders):
        lines.append("## %s\n" % folder)
        for d in sorted(folders[folder], key=lambda x: x.rel):
            lines.append("- [%s](../%s) - %s" % (d.meta["title"], d.rel[len("knowledge/"):], truncate(str(d.meta["summary"]), 160)))  # type: ignore[index]
        lines.append("")
    files["notes.md"] = "\n".join(lines)

    # --- pattern-index.json --------------------------------------------------
    records = []
    for p in patterns:
        records.append({
            "id": p["id"], "title": p["title"], "category": p["category"], "summary": p["summary"], "tags": p.get("tags", []),
            "frameworks": p.get("frameworks", []), "dependencies": p.get("dependencies", []), "source_ids": p.get("source_ids", []),
            "license_status": p["license_status"], "redistribution_status": p["redistribution_status"], "reuse": p["reuse"],
            "implementation_status": p["implementation_status"], "gpu_intensity": (p.get("performance") or {}).get("gpu_intensity"),
            "motion": (p.get("accessibility") or {}).get("motion"), "reduced_motion_alternative": (p.get("accessibility") or {}).get("reduced_motion_alternative"),
            "knowledge_doc": p.get("knowledge_doc"), "recipe": p.get("recipe"), "source_paths": p.get("source_paths", []),
        })
    files["pattern-index.json"] = json.dumps({"version": 1, "patterns": records}, indent=1, sort_keys=True, ensure_ascii=False) + "\n"

    # --- README.md -----------------------------------------------------------
    cat_counts = ", ".join("%s %d" % (c, sum(1 for p in patterns if p["category"] == c)) for c in cats)
    files["README.md"] = (
        HEADER + "# Pattern index\n\n"
        "Browsable views of `catalog/patterns.yaml` (and `catalog/patterns.d/`) plus the knowledge notes.\n\n"
        "- %d patterns, %d knowledge notes, %d sources\n- Categories: %s\n\n"
        "| View | What it lists |\n| --- | --- |\n"
        "| [by-category.md](by-category.md) | every pattern grouped by category, with licence status and reuse class |\n"
        "| [by-source.md](by-source.md) | every source with its licence, patterns and notes |\n"
        "| [by-framework.md](by-framework.md) | patterns per framework or library |\n"
        "| [by-tag.md](by-tag.md) | patterns per tag |\n"
        "| [notes.md](notes.md) | all knowledge notes |\n"
        "| [pattern-index.json](pattern-index.json) | the same data as JSON for tools |\n\n"
        "Search from the command line: `design-sensei search \"<words>\"`.\n" % (len(patterns), len(docs), len(sources), cat_counts)
    )
    return files


def write_docs(layout: Layout) -> List[str]:
    out_dir = layout.knowledge_dir / "pattern-index"
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in sorted(generate_docs(layout).items()):
        (out_dir / name).write_text(text, encoding="utf-8")
        written.append("knowledge/pattern-index/" + name)
    return written


def stale_docs(layout: Layout) -> List[str]:
    out_dir = layout.knowledge_dir / "pattern-index"
    stale = []
    for name, text in sorted(generate_docs(layout).items()):
        path = out_dir / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            stale.append("knowledge/pattern-index/" + name)
    return stale


def cmd_build(layout: Layout, args: argparse.Namespace) -> int:
    if args.check:
        stale = stale_docs(layout)
        if stale:
            eprint("pattern index is out of date: %s\nregenerate with: design-sensei index build --docs" % ", ".join(stale))
            return EXIT_FAILURE
        print("pattern index is up to date")
        return EXIT_OK
    status = 0
    if not args.docs_only:
        index = index_sources.build_index(layout, args.ids)
        path = index_sources.write_index(layout, index)
        total = sum(e["file_count"] for e in index["sources"].values())
        print("source index: %d source(s), %d file(s) -> %s" % (len(index["sources"]), total, path))
        if not index["sources"]:
            print("  (no sources downloaded yet; run `design-sensei setup --full` or `design-sensei sources sync <id>`)")
    if args.docs or args.docs_only:
        try:
            written = write_docs(layout)
        except OSError as exc:
            return fail("cannot write %s: %s (generating the pattern index is a maintainer task for a git checkout)" % (layout.knowledge_dir / "pattern-index", exc))
        print("pattern index: wrote %d file(s) in knowledge/pattern-index/" % len(written))
    return status


def add_subcommands(subparsers: "argparse._SubParsersAction") -> None:
    p = subparsers.add_parser("build", help="build the source index (and with --docs the pattern index)", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("ids", nargs="*", metavar="ID", help="only index these sources")
    p.add_argument("--docs", action="store_true", help="also regenerate knowledge/pattern-index/ (maintainers)")
    p.add_argument("--docs-only", action="store_true", help="only regenerate knowledge/pattern-index/")
    p.add_argument("--check", action="store_true", help="exit 1 if knowledge/pattern-index/ is not up to date (CI)")
    add_global_options(p)
    p.set_defaults(func=lambda a: run_with_layout(a, cmd_build))


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="build_index.py", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", metavar="COMMAND")
    sub.required = True
    add_subcommands(sub)
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
